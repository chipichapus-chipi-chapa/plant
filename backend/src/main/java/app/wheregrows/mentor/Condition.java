package app.wheregrows.mentor;

/** Условия шагов обучения: что игрок должен сделать в игре. Проверяет сервер по данным игрока. */
public enum Condition {
    /** Создана хотя бы одна привычка (в том числе уже убранная в архив). */
    HABIT_CREATED,
    /** Получена хотя бы одна награда за отметку привычки. */
    REWARD_EARNED,
    /** В саду что-то посажено. */
    PLANTED,
    /** Осмотрено место находки или пробуждён объект мира. */
    WORLD_INTERACTION
}
